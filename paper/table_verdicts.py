"""Results tables for the manuscript, written only from a verdicts file of scripts/analyse.py, so
that no number in the results text is copied by hand.

  python paper/table_verdicts.py results/verdicts_confirmatory.json [out.md]
      default out: paper/manuscript/tables_verdicts.md

Table 1  H1: comparison, n, R with exact 95 % and 90 % intervals, raw and Holm p, class, verdict words.
         H1a (descriptive) and the H1b non-inferiority criterion (upper 95 % and 98.75 % bounds).
Table 2  H3: per cell, violating extrapolation fits / fits, Wilson 95 % interval, class; the
         prediction and whether it is met; the all-task counts as a secondary column.
The summary sentences printed by analyse.py are copied verbatim at the end.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def f2(x):
    return f"{x:.2f}"


def p_fmt(p):
    return f"{p:.2g}" if p >= 0.001 else "< 0.001"


def h1_table(v):
    out = ["| Comparison | n | R | exact 95 % interval | exact 90 % interval | p | p (Holm) | class | verdict |",
           "|---|---|---|---|---|---|---|---|---|"]
    rows = []
    if "H1a" in v.get("descriptive", {}):
        rows.append(("H1a (descriptive)", v["descriptive"]["H1a"], False))
    for h in ("H1b", "H1c", "H1d", "H1e"):
        if h in v.get("H1", {}):
            rows.append((h, v["H1"][h], True))
    for name, r, holm in rows:
        out.append(f"| {name}: P vs {r['X']} | {r['n_materials']} | {f2(r['R'])} | "
                   f"{f2(r['R_ci95'][0])} to {f2(r['R_ci95'][1])} | {f2(r['R_ci90'][0])} to {f2(r['R_ci90'][1])} | "
                   f"{p_fmt(r['p'])} | {p_fmt(r['p_adj']) if holm else 'n/a'} | "
                   f"{r.get('class', 'descriptive') if holm else 'descriptive'} | {r.get('verdict', '') if holm else ''} |")
    nb = v.get("H1b_prediction")
    if nb:
        out += ["", f"H1b non-inferiority (primary claim, margin R < {nb['margin']}): upper exact 95 % bound "
                f"{nb['upper95_R']:.3f}, met: {nb['met']}; upper exact 98.75 % bound {nb['upper98.75_R']:.3f}, "
                f"met: {nb['met_at_98.75']}."]
    return out


def h3_table(v):
    h3 = v["H3"]
    allt = h3.get("cells_all_tasks", {})
    out = ["| Cell | violating / fits (E-high, E-low) | Wilson 95 % | class | all tasks (secondary) |",
           "|---|---|---|---|---|"]
    for c, r in h3["cells"].items():
        a = allt.get(c, {})
        sec = f"{a['violating_in_domain']}/{a['fits']} ({a['class']})" if a else ""
        out.append(f"| {c} | {r['violating_in_domain']}/{r['fits']} | {f2(r['wilson95'][0])} to {f2(r['wilson95'][1])} "
                   f"| {r['class']} | {sec} |")
    out += ["", "Prediction: " + json.dumps(h3.get("prediction"), sort_keys=True),
            "P halt check (all tasks): " + json.dumps(h3.get("P_bug_fits"))]
    return out


def main():
    src = Path(sys.argv[1])
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "paper/manuscript/tables_verdicts.md"
    v = json.loads(src.read_text())
    lines = [f"<!-- generated by paper/table_verdicts.py from {src.as_posix()}; do not edit by hand -->", "",
             "## Table 1. Extrapolation accuracy (H1)", ""] + h1_table(v)
    lines += ["", "## Table 2. Thermodynamic violations (H3)", ""] + h3_table(v)
    s = v.get("summary")
    if s:
        lines += ["", "## Summary sentences (analyse.py, verbatim)", ""]
        lines += [f"- {x}" for x in (s if isinstance(s, list) else [s])]
    dst.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(dst)


if __name__ == "__main__":
    main()
