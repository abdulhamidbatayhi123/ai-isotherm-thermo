"""Export the isotherm point lists whose sources allow redistribution (written 2026-11-12, after the verdicts; the
data themselves are unchanged: an exact subset of the frozen data set data/raw/dataset/isotherms.csv).

JCIM's data policy (editorial doi:10.1021/acs.jcim.0c01389) asks that data needed to reproduce the essential results
be public, or extractable by scripts from freely available sources. The confirmatory and development sets are
third-party data. The sources below are published under CC BY 4.0 (licence read from Crossref on 2026-11-12), so their
digitised point lists are redistributed here with attribution. The others are not: the NIST/ARPA-E database records
(ISODB, NIST SRD 205; "All rights reserved" notice on the records) and figures under ACS AuthorChoice, CC BY-NC-ND or
standard ACS licences. They are regenerated by the repository's scripts from the free sources where these exist
(see data/open/README.md).

    python scripts/export_open_data.py   -> data/open/isotherms_open.csv, data/open/SHA256SUMS
"""
import hashlib
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
OPEN_SOURCES = {   # source key -> (DOI of the source, figure digitised, licence of that source)
    "schweng2024_sulfoCOF": ("10.26434/chemrxiv-2023-mlmlv", "ChemRxiv v1 SI Fig. S2 (published as "
                             "doi:10.1002/cssc.202301906, also CC BY 4.0)", "CC BY 4.0"),
    "grunenberg2023_PI-3-COF": ("10.1021/jacs.3c02572", "SI Fig. S34", "CC BY 4.0"),
    "grunenberg2023_NO-PI-3-COF": ("10.1021/jacs.3c02572", "SI Fig. S34", "CC BY 4.0"),
    "tan2021_fig3": ("10.1038/s41467-021-27128-4", "main Fig. 3a-c", "CC BY 4.0"),
    "tan2021_fig4": ("10.1038/s41467-021-27128-4", "main Fig. 4i-k", "CC BY 4.0"),
}


def main():
    # copy the frozen file's lines verbatim (no re-serialisation of numbers), so that any reader parses exactly the
    # values the confirmatory runs used; the source DOI, figure and licence go in data/open/SOURCES.csv
    lines = (ROOT / "data/raw/dataset/isotherms.csv").read_text(encoding="utf-8").splitlines()
    head = lines[0].split(",")
    isrc = head.index("source")
    keep = [ln for ln in lines[1:] if ln.split(",")[isrc] in OPEN_SOURCES]
    missing = set(OPEN_SOURCES) - {ln.split(",")[isrc] for ln in keep}
    if missing:
        sys.exit(f"sources not in the data set: {sorted(missing)}")
    out = ROOT / "data/open"
    out.mkdir(parents=True, exist_ok=True)
    f = out / "isotherms_open.csv"
    f.write_text("\n".join([lines[0]] + keep) + "\n", encoding="utf-8", newline="\n")
    pd.DataFrame([{"source": k, "source_doi": v[0], "source_figure": v[1], "source_licence": v[2]}
                  for k, v in OPEN_SOURCES.items()]).to_csv(out / "SOURCES.csv", index=False, lineterminator="\n")
    sub = pd.read_csv(f)
    h = hashlib.sha256(f.read_bytes()).hexdigest()
    # access route of every material of the frozen data set (data/open/README.md gives the sources)
    access = {"open file": sorted(sub.material.unique())}
    access["script from a free source"] = ["CALF-25", "Zn2(bptc) (Lin 2006)", "Mg-SU-102", "Al-fumarate",
                                           "Co2Cl2(BTDD)", "COF-482-hydrazide", "CuBTC", "MIL-100", "MIL-160"]
    access["subscription source"] = ["COF-432"]
    full = pd.read_csv(ROOT / "data/raw/dataset/isotherms.csv")
    allm = {(m, s) for m, s in full[["material", "set"]].drop_duplicates().itertuples(index=False)}
    listed = [m for v in access.values() for m in v]
    if sorted(listed) != sorted(m for m, _ in allm) or len(set(listed)) != len(listed):
        sys.exit("access table does not cover every material exactly once")
    setof = dict(allm)
    import json
    # largest measured uptake at each material's highest temperature (the E-high held-out isotherm), for the text
    top = {m: float(g[g.T_K == g.T_K.max()].q_molkg.max()) for m, g in sub.groupby("material")}
    summ = {"sha256_open_file": h, "points_open": int(len(sub)), "max_q_at_highest_T_molkg": top,
            "routes": {k: {"confirmatory": sum(setof[m] == "confirmatory" for m in v),
                           "development": sum(setof[m] == "development" for m in v), "materials": v}
                       for k, v in access.items()}}
    (out / "summary.json").write_text(json.dumps(summ, indent=1), encoding="utf-8")
    (out / "SHA256SUMS").write_text(f"{h}  isotherms_open.csv\n", encoding="utf-8")
    print(f"{len(sub)} points, {sub.material.nunique()} materials:", sorted(sub.material.unique()))
    print(sub.groupby(["set", "material"]).size().to_string())
    print("sha256", h)


if __name__ == "__main__":
    main()
